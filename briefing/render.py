"""Render the morning "What moved" briefing and post it to vaultwriter.

Shape (locked in PLAN.md): top-5 ranked across all lanes, then a one-line
digest per lane ("quiet day" counts as signal). Reads brain-data/curated.sqlite;
writes the vault ONLY through vaultwriter's /briefing endpoint.

Usage: python -m briefing.render [--hours 24] [--stdout]
"""

import argparse
import datetime
import json
import time
import urllib.request

from brain import config, db

LANE_LABELS = {
    "papers": "Papers",
    "benchmarks": "Benchmarks",
    "ai-ml": "AI/ML",
    "systems": "Systems/GPU",
    "markets": "Markets",
    "causal-stats": "Causal & Stats",
    "data-eng": "Data Eng",
    "tech": "Tech",
}
QUIET_SCORE = 6.0  # below this, a lane had no genuinely notable item


def _course_short_title(raw: str) -> str:
    """Human title from Learn-hub archive-style names ("Title -- Author -- … -- Anna's
    Archive") — first segment, '_ ' unsanitized back to ': ' (mirrors the hub's own cleaner)."""
    name = (raw or "").strip()
    if " -- " in name:
        name = name.split(" -- ")[0]
    return name.replace("_ ", ": ").strip() or raw


def study_debt_lines() -> list[str]:
    """The Learn hub's review debt as briefing lines — the daily surface is what turns
    spaced repetition from a feature into a habit. Silently absent when the hub is down
    or nothing is tracked (mirrors the stocklake bridge: never break the briefing)."""
    try:
        with urllib.request.urlopen(f"{config.LEARN_URL}/api/study-debt", timeout=10) as r:
            debt = json.loads(r.read().decode())
    except Exception:
        return []
    if debt.get("error") or not debt.get("tracked"):
        return []
    due, soon = int(debt.get("dueNow") or 0), int(debt.get("fadingSoon") or 0)
    lines = ["", "## Study debt", ""]
    if due == 0 and soon == 0:
        lines.append("- **Caught up.** Nothing due, nothing fading this week.")
        return lines
    per_course = " · ".join(
        f"{_course_short_title(c['title'])} {c['dueNow']}"
        for c in debt.get("courses", [])
        if c.get("dueNow")
    )
    if due:
        lines.append(
            f"- **{due} concept{'s' if due != 1 else ''} due now**"
            + (f" ({per_course})" if per_course else "")
            + " — [study](http://localhost:3001)"
        )
    if soon:
        lines.append(f"- {soon} more fade over the next {int(debt.get('days') or 7)} days.")
    return lines


def build(hours: int) -> str:
    con = db.connect()
    since = int(time.time()) - hours * 3600
    # Papers get their own section; keep them out of the news top-5 so a batch
    # of on-niche arXiv 9s can't bury the day's actual news.
    top = [r for r in db.top_since(con, since, 25)
           if r["score"] >= 5.0 and r["lane"] != "papers"][:5]
    lines = [
        f"#briefing · auto-generated by feedwall {datetime.date.today().isoformat()}",
        "",
        "## What moved",
        "",
    ]
    if top:
        for r in top:
            lines.append(
                f"1. **[{r['title']}]({r['url']})** — {r['tldr']} "
                f"`{r['score']:.0f}/10 · {LANE_LABELS.get(r['lane'], r['lane'])} · {r['feed']}`"
            )
    else:
        lines.append("*Nothing cleared the bar today — genuinely quiet.*")
    papers = db.lane_top_since(con, "papers", since, 5)
    if papers:
        lines += ["", "## Papers", ""]
        for r in papers:
            lines.append(
                f"1. **[{r['title']}]({r['url']})** — {r['tldr']} `{r['score']:.0f}/10`"
            )
    lines += ["", "## Lanes", ""]
    top_ids = {r["id"] for r in top}
    for lane in config.LANES:
        if lane == "papers":
            continue  # has its own section above
        best = db.lane_best_since(con, lane, since)
        label = LANE_LABELS[lane]
        if best is None or best["score"] < QUIET_SCORE:
            lines.append(f"- **{label}:** quiet day.")
        elif best["id"] in top_ids:
            lines.append(f"- **{label}:** covered above.")
        else:
            lines.append(
                f"- **{label}:** [{best['title']}]({best['url']}) — {best['tldr']}"
            )
    lines += study_debt_lines()
    scored = con.execute(
        "SELECT COUNT(*) c FROM items WHERE scored_at >= ?", (since,)
    ).fetchone()["c"]
    lines += [
        "",
        f"*{scored} items scored this window · firehose: http://localhost:8970 · "
        "wall: http://localhost:8975*",
    ]
    return "\n".join(lines)


def post(body: str) -> str:
    req = urllib.request.Request(
        f"{config.VAULTWRITER_URL}/briefing",
        data=json.dumps({"body": body, "title": "Daily Briefing"}).encode(),
        headers={"Content-Type": "application/json"},
    )
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode())["path"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--hours", type=int, default=24)
    ap.add_argument("--stdout", action="store_true",
                    help="print instead of posting to vaultwriter")
    args = ap.parse_args()
    body = build(args.hours)
    if args.stdout:
        print(body)
    else:
        print(f"briefing written: {post(body)}")


if __name__ == "__main__":
    main()
