"""Render the morning "What moved" briefing and post it to the briefing sink.

Shape (locked in PLAN.md): top-5 ranked across all lanes, then a one-line
digest per lane ("quiet day" counts as signal). Reads the scored-items DB
(FEEDWALL_DB, default brain-data/curated.sqlite). Without --stdout it POSTs the
Markdown to FEEDWALL_VAULTWRITER_URL/briefing, a small local service that saves
it as a note in the author's Obsidian notes folder ("vault"); feedwall never
writes notes files itself.

Usage: python -m briefing.render [--hours 24] [--stdout] [--as-of YYYY-MM-DD[THH:MM]]
"""

import argparse
import datetime
import json
import time
import urllib.request

from brain import config, db

LANE_LABELS = {
    "papers": "Papers",
    "benchmarks": "Benchmarks",
    "ai-ml": "AI/ML",
    "systems": "Systems/GPU",
    "markets": "Markets",
    "causal-stats": "Causal & Stats",
    "data-eng": "Data Eng",
    "tech": "Tech",
}
QUIET_SCORE = 6.0  # below this, a lane had no genuinely notable item


def _score_tag(r) -> str:
    """`7/10`, or `7/10 fallback` when the model never scored the item."""
    tag = f"{r['score']:.0f}/10"
    if r["score_source"] == "fallback":
        tag += " fallback"
    return tag


def _course_short_title(raw: str) -> str:
    """Human title from Learn-hub archive-style names ("Title -- Author -- … -- Anna's
    Archive") — first segment, '_ ' unsanitized back to ': ' (mirrors the hub's own cleaner)."""
    name = (raw or "").strip()
    if " -- " in name:
        name = name.split(" -- ")[0]
    return name.replace("_ ", ": ").strip() or raw


def study_debt_lines() -> list[str]:
    """The Learn hub's review debt as briefing lines — the daily surface is what turns
    spaced repetition from a feature into a habit. Silently absent when the hub is down
    or nothing is tracked (mirrors the stocklake bridge: never break the briefing).
    Opt-in: returns nothing unless FEEDWALL_STUDY_DEBT is set."""
    if not config.STUDY_DEBT_ENABLED:
        return []
    try:
        with urllib.request.urlopen(f"{config.LEARN_URL}/api/study-debt", timeout=10) as r:
            debt = json.loads(r.read().decode())
    except Exception:
        return []
    if debt.get("error") or not debt.get("tracked"):
        return []
    due, soon = int(debt.get("dueNow") or 0), int(debt.get("fadingSoon") or 0)
    lines = ["", "## Study debt", ""]
    if due == 0 and soon == 0:
        lines.append("- **Caught up.** Nothing due, nothing fading this week.")
        return lines
    per_course = " · ".join(
        f"{_course_short_title(c['title'])} {c['dueNow']}"
        for c in debt.get("courses", [])
        if c.get("dueNow")
    )
    if due:
        lines.append(
            f"- **{due} concept{'s' if due != 1 else ''} due now**"
            + (f" ({per_course})" if per_course else "")
            + f" — [study]({config.LEARN_UI_URL})"
        )
    if soon:
        lines.append(f"- {soon} more fade over the next {int(debt.get('days') or 7)} days.")
    return lines


def build(hours: int, as_of: datetime.datetime | None = None) -> str:
    """Render the briefing for the `hours` before `as_of` (default: now)."""
    con = db.connect()
    now = int(as_of.timestamp()) if as_of else int(time.time())
    until = now if as_of else None
    since = now - hours * 3600
    day = (as_of.date() if as_of else datetime.date.today()).isoformat()
    # Papers get their own section; keep them out of the news top-5 so a batch
    # of on-niche arXiv 9s can't bury the day's actual news.
    top = [r for r in db.top_since(con, since, 25, until=until)
           if r["score"] >= 5.0 and r["lane"] != "papers"][:5]
    lines = [
        f"#briefing · auto-generated by feedwall {day}",
        "",
        "## What moved",
        "",
    ]
    if top:
        for r in top:
            lines.append(
                f"1. **[{r['title']}]({r['url']})** — {r['tldr'] or '(no summary)'} "
                f"`{_score_tag(r)} · {LANE_LABELS.get(r['lane'], r['lane'])} · {r['feed']}`"
            )
    else:
        lines.append("*Nothing cleared the bar today — genuinely quiet.*")
    papers = db.lane_top_since(con, "papers", since, 5, until=until)
    if papers:
        lines += ["", "## Papers", ""]
        for r in papers:
            lines.append(
                f"1. **[{r['title']}]({r['url']})** — {r['tldr']} `{_score_tag(r)}`"
            )
    lines += ["", "## Lanes", ""]
    top_ids = {r["id"] for r in top}
    for lane in config.LANES:
        if lane == "papers":
            continue  # has its own section above
        best = db.lane_best_since(con, lane, since, until=until)
        label = LANE_LABELS[lane]
        if best is None or best["score"] < QUIET_SCORE:
            lines.append(f"- **{label}:** quiet day.")
        elif best["id"] in top_ids:
            lines.append(f"- **{label}:** covered above.")
        else:
            lines.append(
                f"- **{label}:** [{best['title']}]({best['url']}) — {best['tldr']}"
            )
    lines += study_debt_lines()
    scored = con.execute(
        "SELECT COUNT(*) c FROM items WHERE scored_at BETWEEN ? AND ?",
        (since, until or db._NO_BOUND),
    ).fetchone()["c"]
    con.close()
    lines += [
        "",
        f"*{scored} items scored this window · firehose: http://localhost:8970 · "
        "wall: http://localhost:8975*",
    ]
    return "\n".join(lines)


def post(body: str) -> str:
    req = urllib.request.Request(
        f"{config.VAULTWRITER_URL}/briefing",
        data=json.dumps({"body": body, "title": "Daily Briefing"}).encode(),
        headers={"Content-Type": "application/json"},
    )
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode())["path"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--hours", type=int, default=24)
    ap.add_argument("--stdout", action="store_true",
                    help="print instead of posting to the briefing sink")
    ap.add_argument("--as-of", type=datetime.datetime.fromisoformat, default=None,
                    help="render as if it were this ISO date/time (replay or demo DB)")
    args = ap.parse_args()
    body = build(args.hours, args.as_of)
    if args.stdout:
        print(body)
    else:
        path = post(body)
        # The wall's /health briefing check keys off this — only a successful
        # post counts, so eight silent days of a dead vaultwriter read as stale.
        con = db.connect()
        db.set_meta(con, "last_briefed",
                    datetime.datetime.now().astimezone().isoformat(timespec="seconds"))
        con.commit()
        con.close()
        print(f"briefing written: {path}")


if __name__ == "__main__":
    main()
