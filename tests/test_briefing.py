"""Briefing render against the committed synthetic demo DB."""
import datetime
import subprocess
import sys

from brain import config
from briefing import render
from tests.conftest import DEMO_DB, ROOT, fake_json_response

AS_OF = datetime.datetime(2026, 1, 15, 7, 0, tzinfo=datetime.timezone.utc)


def test_render_shape(demo_db):
    out = render.build(24, AS_OF)
    assert out.startswith("#briefing · auto-generated by feedwall 2026-01-15")
    sections = [line for line in out.splitlines() if line.startswith("## ")]
    assert sections == ["## What moved", "## Papers", "## Lanes"]
    what_moved = out.split("## What moved")[1].split("## Papers")[0]
    assert what_moved.count("\n1. ") == 5          # top-5, no more
    assert "Demo paper" not in what_moved          # papers kept out of the news top-5
    assert "(outside the window)" not in out       # 7-day-old item excluded
    assert "ten gadgets" not in out                # 2/10 never surfaces


def test_top_item_ranked_first(demo_db):
    out = render.build(24, AS_OF)
    first = out.split("## What moved")[1].strip().splitlines()[0]
    assert "7B model matches a 70B baseline" in first and "`9/10 · AI/ML" in first


def test_fallback_score_is_labelled(demo_db):
    out = render.build(24, AS_OF)
    line = next(l for l in out.splitlines() if "failed to score" in l)
    assert "7/10 fallback" in line and "(no summary)" in line
    # model-scored items carry no fallback tag
    assert "9/10 fallback" not in out


def test_lanes_quiet_and_covered(demo_db):
    out = render.build(24, AS_OF)
    assert "- **Causal & Stats:** quiet day." in out
    assert "- **Tech:** quiet day." in out          # only a 2/10 arrived
    assert "- **AI/ML:** covered above." in out
    assert "- **Data Eng:** [Demo: a columnar format" in out


def test_scored_count_respects_window(demo_db):
    assert "*10 items scored this window" in render.build(24, AS_OF)


def test_study_debt_off_by_default(demo_db, monkeypatch):
    def boom(*a, **k):
        raise AssertionError("study service must not be called when disabled")
    monkeypatch.setattr(render.urllib.request, "urlopen", boom)
    assert config.STUDY_DEBT_ENABLED is False
    assert "Study debt" not in render.build(24, AS_OF)


def test_study_debt_opt_in(demo_db, monkeypatch):
    monkeypatch.setattr(config, "STUDY_DEBT_ENABLED", True)
    monkeypatch.setattr(render.urllib.request, "urlopen", lambda *a, **k: fake_json_response(
        {"tracked": 3, "dueNow": 2, "fadingSoon": 1, "days": 7,
         "courses": [{"title": "Stats -- Someone -- x", "dueNow": 2}]}))
    out = render.build(24, AS_OF)
    assert "## Study debt" in out
    assert "**2 concepts due now** (Stats 2)" in out


def test_cli_stdout_on_demo_db_does_not_modify_it():
    before = DEMO_DB.read_bytes()
    env = {"FEEDWALL_DB": str(DEMO_DB), "PATH": "/usr/bin:/bin"}
    res = subprocess.run(
        [sys.executable, "-m", "briefing.render", "--stdout",
         "--as-of", "2026-01-15T07:00+00:00"],
        cwd=ROOT, env=env, capture_output=True, text=True, check=True)
    assert "## What moved" in res.stdout
    assert DEMO_DB.read_bytes() == before
